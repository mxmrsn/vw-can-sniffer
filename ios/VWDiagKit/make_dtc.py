"""Regenerate Sources/VWDiagKit/DTCDescriptions.swift from the tools' fault-code lists.

    python3 ios/VWDiagKit/make_dtc.py        (from the repository root)

The groups and the order of preference are the tools' (tools/vwdiag/dtc.py), so the app and
the tools describe every code the same way.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
from vwdiag import dtc  # noqa: E402


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = ["// Fault-code descriptions, generated by ios/VWDiagKit/make_dtc.py from",
             "// tools/vwdiag/data/dtc_generic.csv (dtcdb, MIT licence: tools/vwdiag/data/LICENSE.dtcdb) and",
             "// tools/vwdiag/data/dtc_extra.csv (written for this project from the SAE J2012 code titles).",
             "",
             "public enum DTCDescriptions {",
             "    /// The generic list first, then the added codes; see `FaultCode.describe`.",
             "    static let generic: [String: String] = ["]
    lines += ["        %s: %s," % (lit(c), lit(d)) for c, d in sorted(dtc.GENERIC.items())]
    lines += ["    ]", "    static let extra: [String: String] = ["]
    lines += ["        %s: %s," % (lit(c), lit(d)) for c, d in sorted(dtc.EXTRA.items())]
    lines += ["    ]", "    /// SAE J2012 blocks; the longest matching prefix wins.", "    static let groups: [(String, String)] = ["]
    lines += ["        (%s, %s)," % (lit(p), lit(m)) for p, m in dtc.GROUPS]
    lines += ["    ]", "}", ""]
    out = os.path.join(HERE, "Sources", "VWDiagKit", "DTCDescriptions.swift")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote %d + %d codes, %d groups to %s" % (len(dtc.GENERIC), len(dtc.EXTRA), len(dtc.GROUPS), out))


if __name__ == "__main__":
    main()
